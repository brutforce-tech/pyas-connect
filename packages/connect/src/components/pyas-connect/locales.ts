/** A language tag as one of ours, or null: `nb-NO`, `no` and `nn` are Norwegian Bokmål, any `pt` is Brazil's. */
export const matchLocale = (tag: string | null | undefined): Locale | null => {
    const lower = String(tag ?? '').trim().toLowerCase().replace('_', '-')
    if (!lower) return null
    const language = lower.split('-')[0]
    if (language === 'no' || language === 'nn' || language === 'nb') return 'nb'
    if (language === 'pt') return 'pt-BR'
    return (LOCALES as readonly string[]).includes(language) ? language as Locale : null
}

/** The first language we have among those given, in order; English when none is ours. */
export const resolveLocale = (...candidates: Array<string | null | undefined>): Locale => {
    for (const candidate of candidates) {
        const found = matchLocale(candidate)
        if (found) return found
    }
    return 'en'
}
